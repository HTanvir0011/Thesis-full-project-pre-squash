def reliability():
    u = json.loads((R / "unc_heldout.json").read_text())
    s, r = np.asarray(u["synth_items"]), np.asarray(u["real_items"])
    fig, ax = plt.subplots(1, 2, figsize=(5.6, 2.4))
    ax[0].axhline(1 - u["alpha"], color=INK, ls="--", lw=1, label="nominal 0.90")
    for k, (v, lab, c) in enumerate(((s[:, 0], f"Qure-projection test (n={len(s)})", BLUE), (r[:, 0], f"SZCH held-out (n={len(r)})", ORANGE))):
        ax[0].scatter(k + np.random.default_rng(0).uniform(-0.15, 0.15, len(v)), v, s=6, color=c, alpha=0.5, lw=0)
        ax[0].plot([k - 0.25, k + 0.25], [v.mean()] * 2, color=c, lw=2)
    ax[0].set_xticks([0, 1], ["synthetic\n(exact truth)", "real pairs\n(under shift)"])
    ax[0].set_ylabel("per-image interval coverage")
    ax[0].set_ylim(0, 1.02)
    ax[0].legend(frameon=False, fontsize=7, loc="center right")
    ax[1].hist(r[:, 2], bins=15, color=ORANGE, alpha=0.8)
    ax[1].axvline(r[:, 2].mean(), color=INK, lw=1)
    ax[1].set_xlabel("Spearman(spread, |error|) per SZCH image")
    ax[1].set_ylabel("images")
    save(fig, "reliability")


def audit_map(n_sites=8):
    """Illustration of the audit on one SZCH held-out image (the median of ours' bone PSNR) with the test-library lesion of median diameter.
    Not hand-picked: n_sites placements are drawn (seed 7) among lung pixels inside the DES bone map (pinned masks of the final audit), and the
    placement with the median A(ours) - A(Qure) is shown, so the example is typical of the contrast rather than its best case."""
    import cv2
    from s4 import lesion_lib
    from s4.audit_real import SIZE, bone_fn, load_images
    from szch_split import is_dev
    s = pd.read_csv(R / "szch" / "ours.csv")
    s = s[~s.image.map(is_dev)].sort_values("psnr_cal_bone").reset_index(drop=True)
    name = s.image[round(0.5 * (len(s) - 1))]
    pairs = {n: (x, b) for n, x, b in load_images("szch", str(ROOT / "data" / "szch"))}
    z = np.load(ROOT / "outputs" / "audit_masks" / "szch.npz")
    lung = np.unpackbits(z["lung"][list(z["names"]).index(name)], count=SIZE * SIZE).reshape(SIZE, SIZE) > 0
    x, bone = pairs[name]
    lib = lesion_lib.load(str(ROOT / "outputs" / "lesions_test.npz"))
    les = lib[int(np.argsort([v["diam_mm"] for v in lib])[len(lib) // 2])]
    patch = cv2.resize(les["x_patch"], None, fx=2.0, fy=2.0, interpolation=cv2.INTER_LINEAR)
    h, w = patch.shape
    ys, xs = np.nonzero(lung & bone)
    ys, xs = ys[(ys > h) & (ys < SIZE - h) & (xs > w) & (xs < SIZE - w)], xs[(ys > h) & (ys < SIZE - h) & (xs > w) & (xs < SIZE - w)]
    W = ROOT / "outputs" / "final_v2" / "weights"
    specs = {"ours (K=3)": "ens:" + "+".join(str(W / f"qp_twin16_s{i}_cnx2_300k" / "final_ema.pt") for i in range(3)),
             "no twin (K=3)": "ens:" + "+".join(str(W / f"qp_s{i}_cnx2_300k" / "final_ema.pt") for i in range(3)),
             "Qure": "qure:" + str(ROOT / "data" / "qure" / "weights" / "bone_suppression.ts")}
    fns = {lab: bone_fn(spec, "cpu") for lab, spec in specs.items()}
    b0 = {lab: f(x) for lab, f in fns.items()}
    sites = []
    for j in np.random.default_rng(7).choice(len(ys), n_sites, replace=False):
        n = np.zeros((SIZE, SIZE), np.float32)
        n[ys[j] - h // 2:ys[j] - h // 2 + h, xs[j] - w // 2:xs[j] - w // 2 + w] = patch
        sup, xp = n > 0.02 * n.max(), np.clip(x + n, 0, 1).astype(np.float32)
        db = {lab: f(xp) - b0[lab] for lab, f in fns.items()}
        A = {lab: float((d * n)[sup].sum() / (n[sup] ** 2).sum()) for lab, d in db.items()}
        sites.append(dict(y=ys[j], x=xs[j], n=n, xp=xp, db=db, A=A))
    gap = [st["A"]["ours (K=3)"] - st["A"]["Qure"] for st in sites]
    st = sites[int(np.argsort(gap)[len(gap) // 2])]
    print("audit map:", name, "A(ours)-A(Qure) per placement", np.round(sorted(gap), 3), "shown", round(st["A"]["ours (K=3)"] - st["A"]["Qure"], 3))
    c = 72
    crop = lambda im: im[st["y"] - c:st["y"] + c, st["x"] - c:st["x"] + c]  # noqa: E731
    win = lambda im: dict(cmap="gray", vmin=np.percentile(crop(im), 1), vmax=np.percentile(crop(im), 99))  # noqa: E731
    vmax = float(st["n"].max())
    fig, ax = plt.subplots(2, 4, figsize=(7.2, 4.6))
    ax[0, 0].imshow(crop(st["xp"]), **win(st["xp"]))
    ax[0, 0].set_title("radiograph with\ninserted lesion", fontsize=7)
    ax[1, 0].imshow(crop(st["n"]), cmap="gray", vmin=0, vmax=vmax)
    ax[1, 0].set_title(f"inserted lesion\n({les['diam_mm']:.0f} mm, LIDC test CT)", fontsize=7)
    for col, lab in enumerate(specs, start=1):
        ax[0, col].imshow(crop(st["db"][lab]), cmap="RdBu_r", vmin=-vmax, vmax=vmax)
        ax[0, col].set_title(f"{lab}\nbone change, A = {st['A'][lab]:.2f}", fontsize=7)
        soft = np.clip(st["xp"] - (st["db"][lab] + b0[lab]), 0, 1)
        ax[1, col].imshow(crop(soft), **win(soft))
        ax[1, col].set_title(f"{lab}\nsoft image", fontsize=7)
    for a in ax.ravel():
        a.set_axis_off()
    fig.suptitle(f"SZCH-X-Rays {name} (CC BY-NC 4.0); colour scale of the bone change = lesion amplitude", fontsize=7, color=MUTED)
    save(fig, "audit_maps")


def additivity_gap():
    """Beam hardening: relative gap (P_bone + P_soft - P_joint) / P_joint of separately projected components (s4/xray.py tables)."""
    from s4 import xray
    t = xray.tables()
    E, mu = np.array(t["energy_keV"]), {m: np.array(t["mu_over_rho_cm2_per_g"][m]) for m in ("bone_cortical", "soft_tissue")}

    def gap(kvp, a_s, a_b):
        w = xray.spectrum(kvp) * E
        P = lambda att: -np.log((w * np.exp(-att)).sum() / w.sum())  # noqa: E731
        joint = P(mu["soft_tissue"] * a_s + mu["bone_cortical"] * a_b)
        return (P(mu["soft_tissue"] * a_s) + P(mu["bone_cortical"] * a_b) - joint) / joint
    assert abs(gap(100, 20.0, 3.0) - 0.061) < 0.0015, gap(100, 20.0, 3.0)  # the value quoted in paper/sections/methods.tex
    a_s = np.linspace(0.5, 30, 60)
    fig, ax = plt.subplots(1, 3, figsize=(7.2, 2.5), sharey=True)
    for k, kvp in enumerate((80, 100, 130)):
        for a_b, c in ((1.0, AQUA), (3.0, BLUE), (5.0, ORANGE)):
            ax[k].plot(a_s, [100 * gap(kvp, s, a_b) for s in a_s], color=c, lw=1.6, label=f"bone {a_b:.0f} g/cm$^2$")
        ax[k].set_title(f"{kvp} kVp", fontsize=8)
        ax[k].set_xlabel("soft tissue (g/cm$^2$)")
        ax[k].grid(True, color="#e6e5e1", lw=0.6)
    ax[0].set_ylabel("additivity gap (% of joint $P$)")
    ax[0].legend(frameon=False, fontsize=7)
    save(fig, "additivity_gap")


def v1_tables(st):
    """SAP.md H1 (v1 family): the planned test on synthetic test CTs (results/ablation_test, 200k samples, 3 seeds per arm, made 2026-10-27 by
    tools/aggregate_ablation.py) with the 300k-sample finals as a replication; and the selection on validation CTs (results/ablation_val)."""
    nice = {"clia": "CLIA (insertion)", "nodule_loss": "lesion-weighted loss", "clia_nodule": "CLIA + lesion-weighted loss", "nofreq": "no frequency loss",
            "nohist": "no histogram matching", "nomark": "no marking-ROI loss", "rot0": "no rotation"}
    for split, arms, name, cap in (("ablation_test", ("clia", "nodule_loss", "clia_nodule"), "v1_h1",
                                    "First analysis plan, H1: lesion-aware arms against the recipe arm on synthetic LIDC test CTs (3 seeds each, 200k samples), "
                                    "and the 300k-sample finals of CLIA and recipe as a replication. Holm over the seven contrasts of the v1 ablation."),
                                   ("ablation_val", tuple(nice), "v1_ablation_val",
                                    "v1 ablation on synthetic validation CTs (selection data; 3 seeds each, 200k samples): every arm against the recipe arm.")):
        c = pd.read_csv(ROOT / "results" / split / "contrasts_synth.csv").set_index("arm")
        rows = [[nice[a], int(c.n_sites[a]), ci_str(-c.absorption_reduction[a], -c.ci_hi[a], -c.ci_lo[a]), f"{c.holm_p[a]:.2g}",
                 f"{c.mae_lower_bound[a]:.5f} vs $-${c.mae_margin[a]:.5f}", "yes" if c.mae_non_inferior[a] else "no"] for a in arms]
        if split == "ablation_test" and isinstance(st.get("H1_v1_synth"), dict):
            v = st["H1_v1_synth"]
            rows.append(["CLIA, 300k finals (replication)", v["n_ct_A"], ci_str(*v["A_diff"]), f"{v['A_p']:.2g} (Wilcoxon)",
                         f"{v['mae_noninferior']['lower']:.5f} vs $-${v['mae_noninferior']['margin']:.5f}", "yes" if v["mae_noninferior"]["non_inferior"] else "no"])
        tex(TAB / f"{name}.tex", ["arm vs recipe", "sites / CTs", "$\\Delta A$ [95\\% CI]", "Holm $p$", "bone-MAE lower bound vs margin", "MAE non-inferior"], rows, cap)


