def dose_figure(st):
    pts = []
    for w, names in DOSE.items():
        for n in names:
            p = R / "audit_ribcxr" / f"{n}.csv"
            if p.exists():
                pts.append((w, float(pd.read_csv(p).absorption.mean())))
    pts = np.array(pts)
    d = st["H3_ribcxr"]["dose_response"]
    x = np.log2(1 + pts[:, 0])
    m = np.array([d["mean_A"][str(int(w))] for w in sorted(set(pts[:, 0]))])
    xs = np.log2(1 + np.array(sorted(set(pts[:, 0]))))
    b = float(np.mean(m - d["slope"] * xs))  # line through the per-weight means with the pre-registered slope
    fig, ax = plt.subplots(figsize=(3.4, 2.6))
    ax.grid(True, color="#e6e5e1", lw=0.6)
    ax.scatter(x, pts[:, 1], s=16, color=BLUE, alpha=0.5, lw=0, label="one seed")
    ax.plot(xs, m, "o", color=BLUE, ms=6, mec="white", label="seed mean")
    xx = np.linspace(0, xs.max(), 20)
    ax.plot(xx, b + d["slope"] * xx, "--", color=INK, lw=1, label=f"slope {ci_str(d['slope'], *d['ci95'], d=4)}")
    ax.set_xticks(xs, [str(int(w)) for w in sorted(set(pts[:, 0]))])
    ax.set_xlabel("twin weight $w$ (log$_2$(1+$w$) axis)")
    ax.set_ylabel("lesion absorption $A$ (VinDr-RibCXR)")
    ax.legend(frameon=False, fontsize=7)
    save(fig, "dose_response")


